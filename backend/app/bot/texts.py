def admin_panel_text(telegram_id: int, is_admin: bool, has_webapp: bool) -> str:
    if not is_admin:
        return (
            "Панель администратора открывается только для id из ADMIN_TELEGRAM_IDS.\n"
            f"Ваш числовой id: {telegram_id}\n"
            "Запишите его в эту переменную и перезапустите сервер. "
            "Панель не проводит расследование и не показывает зашифрованный контакт."
        )
    if not has_webapp:
        return (
            "Вы администратор. Кнопка в Telegram появится, когда WEBAPP_URL начнётся с https://.\n"
            "Пока панель можно открыть в браузере на своём компьютере."
        )
    return (
        "Панель администратора. Это очередь карточек, а не расследование. "
        "Контакт автора остаётся зашифрованным."
    )


