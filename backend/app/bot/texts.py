from __future__ import annotations

from app.core.config import Settings


def start_text() -> str:
    return (
        "AntiTerror Robot\n"
        "Сообщай. Фиксируй. Защищай.\n\n"
        "Я помогу спокойно зафиксировать сообщение о мошенничестве, вербовке, "
        "шантаже или попытке втянуть человека в противоправные действия.\n\n"
        "Я не полиция и не провожу проверку. Карточка нужна, чтобы вы могли обратиться в МВД.\n\n"
        "Если опасность происходит сейчас — звоните 112 или 102, не ждите ответа бота."
    )


def report_text(settings: Settings) -> str:
    if settings.webapp_url.startswith("https://"):
        return (
            "Откройте приложение и заполните карточку. "
            "Не вставляйте пароли, коды из SMS и номера карт.\n\n"
            "Если угроза происходит сейчас, сначала позвоните 112 или 102."
        )
    return (
        "Приложение ещё не подключено. Сохраните переписку и скриншоты у себя "
        "и обратитесь в полицию по номеру 102. При угрозе жизни звоните 112."
    )


