def evidence_text() -> str:
    return (
        "Как сохранить доказательства\n\n"
        "1. Не удаляйте чат и не редактируйте сообщения.\n"
        "2. Сделайте скриншоты, где видны имя, ссылка, дата и текст.\n"
        "3. Сохраните ссылку на аккаунт или канал.\n"
        "4. Не вступайте в спор и не выполняйте требования.\n"
        "5. Не загружайте интимные материалы. Если шантаж связан с такими файлами, "
        "не присылайте их сюда — отнесите устройство в полицию.\n"
        "6. Не записывайте пароли, коды из SMS, CVV и полные номера карт.\n\n"
        "Копия на вашем устройстве важна: сервис хранит файлы ограниченное время и не заменяет полицию."
    )


def privacy_text(settings: Settings) -> str:
    return (
        "Конфиденциальность\n\n"
        "AntiTerror Robot хранит карточку, чтобы вы могли вернуться к ней и скачать PDF. "
        "Мы не передаём её в полицию и не публикуем.\n\n"
        f"Срок хранения — {settings.retention_days} дней, затем карточка и файлы удаляются. "
        "Удалить раньше можно в приложении.\n\n"
        "Контакт для связи шифруется. Пароли, коды из SMS, CVV, полные номера карт "
        "и интимные материалы сохранять нельзя.\n\n"
        "В журнале действий нет текста сообщения. Это не правоохранительный орган."
    )
